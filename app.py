# --- ESTILOS DE TERMINAL ---
class bcolors:
    HEADER = '\033[95m'
    OKBLUE = '\033[94m'
    OKCYAN = '\033[96m'
    OKGREEN = '\033[92m'
    WARNING = '\033[93m'
    FAIL = '\033[91m'
    ENDC = '\033[0m'
    BOLD = '\033[1m'

# --- RUTAS DE BASE DE DATOS ---
DB = {
    "zonas": 'datos/zonas/db_zonas.json',
    "eventos": 'datos/eventos/db_eventos.json',
    "boletos": 'datos/boletos/db_boletos.json',
    "usuarios": 'datos/usuarios/db_usuarios.json',
    "sesiones": 'datos/sesiones/db_sesiones.json'
}

# --- FUNCIONES DE PERSISTENCIA ---
def hash_password(password):
    return hashlib.sha256(password.encode()).hexdigest()

def cargar(tipo):
    try:
        if not os.path.exists(DB[tipo]): return []
        with open(DB[tipo], 'r', encoding='utf-8') as f:
            content = f.read().strip()
            return json.loads(content) if content else []
    except: return []

def guardar(tipo, datos):
    os.makedirs(os.path.dirname(DB[tipo]), exist_ok=True)
    with open(DB[tipo], 'w', encoding='utf-8') as f:
        json.dump(datos, f, indent=4, ensure_ascii=False)

def inicializar_sistema():
    """Configuración inicial del sistema y carpetas."""
    for path in DB.values():
        os.makedirs(os.path.dirname(path), exist_ok=True)

    if not cargar("usuarios"):
        guardar("usuarios", [{"user": "admin", "pass": hash_password("admin123"), "rol": "admin"}])

    if not cargar("zonas"):
        guardar("zonas", [{"ID_ZONA": "Z1", "Nombre": "General", "Capacidad": "100", "Precio": 15.00}])

    if not cargar("eventos"):
        guardar("eventos", [{"ID_EVENTO": "E1", "Evento": "Concierto Mágico", "Fecha": "2026-06-15"}])

# --- LÓGICA DE VENTA (TODOS LOS CAMPOS) ---
def vender_boleto_completo():
    eventos = cargar("eventos")
    zonas = cargar("zonas")
    boletos = cargar("boletos")

    if not eventos or not zonas:
        print(f"{bcolors.FAIL}❌ Error: Eventos o Zonas no configurados.{bcolors.ENDC}")
        return

    # 1. Selección de Evento
    print(f"\n{bcolors.BOLD}--- EVENTOS DISPONIBLES ---{bcolors.ENDC}")
    print(tabulate(eventos, headers="keys", tablefmt="pretty"))
    id_ev = input("ID de Evento: ").upper().strip()
    evento = next((e for e in eventos if e['ID_EVENTO'] == id_ev), None)
    if not evento: return print(f"{bcolors.FAIL}Evento no encontrado.{bcolors.ENDC}")

    # 2. Selección de Zona
    print(f"\n{bcolors.BOLD}--- ZONAS DISPONIBLES ---{bcolors.ENDC}")
    print(tabulate(zonas, headers="keys", tablefmt="pretty"))
    id_zo = input("ID de Zona: ").upper().strip()
    zona = next((z for z in zonas if z['ID_ZONA'] == id_zo), None)
    if not zona: return print(f"{bcolors.FAIL}Zona no encontrada.{bcolors.ENDC}")

    # 3. Validación de Capacidad
    vendidos_en_zona = len([b for b in boletos if b['ID_ZONA'] == id_zo and b['ID_EVENTO'] == id_ev and b['ESTADO'] == 'VENDIDO'])
    if vendidos_en_zona >= int(zona['Capacidad']):
        return print(f"{bcolors.FAIL}⛔ ZONA AGOTADA.{bcolors.ENDC}")

    try:
        # 4. Captura de Datos del Cliente (Todos los campos)
        print(f"\n{bcolors.OKCYAN}--- DATOS DEL CLIENTE ---{bcolors.ENDC}")
        nombre_cliente = input("Nombre Completo: ").strip()
        dui_cliente = input("DUI / Identificación: ").strip()
        correo_cliente = input("Correo Electrónico: ").strip()

        print(f"\n{bcolors.OKCYAN}--- UBICACIÓN ---{bcolors.ENDC}")
        fila = input("Fila (Ej. A): ").upper().strip()
        asiento = int(input("Número de Asiento: "))
        ubicacion = f"F{fila}-A{asiento}"

        # Validar si el asiento ya existe
        if any(b for b in boletos if b['ID_EVENTO'] == id_ev and b['ID_ZONA'] == id_zo and b['UBICACION'] == ubicacion and b['ESTADO'] == 'VENDIDO'):
            return print(f"{bcolors.WARNING}⚠ El asiento {ubicacion} ya está ocupado.{bcolors.ENDC}")

        # 5. Pago
        precio = float(zona['Precio'])
        print(f"\n{bcolors.OKGREEN}TOTAL A PAGAR: ${precio:.2f}{bcolors.ENDC}")
        metodo_pago = input("Método de Pago (Efectivo/Tarjeta/Bitcoin): ").strip().capitalize()

        # 6. Generación del Registro Completo
        nuevo_boleto = {
            "FOLIO": f"TKT-{str(uuid.uuid4())[:8].upper()}",
            "EVENTO": evento['Evento'],
            "ZONA": zona['Nombre'],
            "UBICACION": ubicacion,
            "CLIENTE": nombre_cliente,
            "DUI": dui_cliente,
            "CORREO": correo_cliente,
            "PRECIO": precio,
            "METODO_PAGO": metodo_pago,
            "FECHA_VENTA": datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
            "ESTADO": "VENDIDO",
            "ID_EVENTO": id_ev,
            "ID_ZONA": id_zo
        }

        boletos.append(nuevo_boleto)
        guardar("boletos", boletos)
        print(f"\n{bcolors.OKGREEN}✅ ¡BOLETO EMITIDO CON ÉXITO!{bcolors.ENDC}")
        print(tabulate([nuevo_boleto], headers="keys", tablefmt="fancy_grid"))

    except ValueError:
        print(f"{bcolors.FAIL}❌ Error: Ingrese datos válidos.{bcolors.ENDC}")

# --- MENÚ PRINCIPAL ---
def menu():
    inicializar_sistema()

    print(f"{bcolors.HEADER}=== SISTEMA DE VENTAS EL MÁGICO ==={bcolors.ENDC}")
    user = input("Usuario: ").strip()
    password = input("Contraseña: ").strip()

    usuarios = cargar("usuarios")
    h_pass = hash_password(password)
    auth = next((u for u in usuarios if u["user"] == user and u["pass"] == h_pass), None)

    if not auth:
        print(f"{bcolors.FAIL}Acceso denegado.{bcolors.ENDC}")
        return

    while True:
        print(f"\n{bcolors.BOLD}BIENVENIDO: {user.upper()} ({auth['rol'].upper()}){bcolors.ENDC}")
        print("1. Ver Eventos")
        print("2. Venta de Boleto (Full Campos)")
        print("3. Listar / Buscar Boletos")

        if auth['rol'] == "admin":
            print("4. Reporte de Ingresos (ADMIN)")
            print("5. Gestión de Zonas y Precios (ADMIN)")

        print("0. Salir")

        op = input("\nSeleccione opción: ")

        if op == '1':
            print(tabulate(cargar("eventos"), headers="keys", tablefmt="fancy_grid"))
        elif op == '2':
            vender_boleto_completo()
        elif op == '3':
            boletos = cargar("boletos")
            if not boletos:
                print("No hay registros.")
            else:
                print(tabulate(boletos, headers="keys", tablefmt="simple"))
        elif op == '4' and auth['rol'] == "admin":
            boletos = cargar("boletos")
            total = sum(float(b['PRECIO']) for b in boletos if b['ESTADO'] == 'VENDIDO')
            print(f"\n{bcolors.OKGREEN}--- REPORTE FINANCIERO ---{bcolors.ENDC}")
            print(f"Total Recaudado: ${total:.2f}")
            print(f"Total Boletos Vendidos: {len([b for b in boletos if b['ESTADO'] == 'VENDIDO'])}")
        elif op == '5' and auth['rol'] == "admin":
            zonas = cargar("zonas")
            print(tabulate(zonas, headers="keys", tablefmt="fancy_grid"))
            if input("¿Agregar zona? (s/n): ").lower() == 's':
                try:
                    zonas.append({
                        "ID_ZONA": f"Z{len(zonas)+1}",
                        "Nombre": input("Nombre de Zona: "),
                        "Capacidad": input("Capacidad: "),
                        "Precio": float(input("Precio ($): "))
                    })
                    guardar("zonas", zonas)
                    print("Zona guardada correctamente.")
                except ValueError:
                    print("Error: El precio debe ser un número.")
        elif op == '0':
            print("Saliendo del sistema...")
            break

if __name__ == "__main__":
    menu()



